#!/usr/bin/env python3
"""Self-test of pin_statements.py on small synthetic chip files.

    python3 crates/fv/lean4/check/test_pin_statements.py
"""
import io
import json
import sys
import tempfile
import unittest
from contextlib import redirect_stderr, redirect_stdout
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import pin_statements as pin  # noqa: E402

HEADER = """/-
  Generated by `cargo run -p zkm-picus -- --chip {chip} --format lean`.
-/
import ZirenDet.Basic

set_option maxHeartbeats 0

namespace ZirenDet.Chips.{chip}

open ZirenDet
"""

HELPER = """
/-! ### Module `byte_and` -/
namespace byte_and

/-- Abstract helper: 2 input(s), 1 output(s). -/
{decl}

end byte_and
"""

MODULE = """
/-! ### Module `{title}` -/
namespace {ns}

/-- The witness row: one field element per variable the module mentions. -/
structure W where
{fields}

/-- Every polynomial identity, range fact and helper-module call of the module. -/
def constraints_0 (w : W) : Prop :=
{constraints}

def constraints (w : W) : Prop :=
  constraints_0 w

def input_origins : List String := {in_origins}
def output_origins : List String := {out_origins}

def inputs (w : W) : List F :=
  [{inputs}]
def outputs (w : W) : List F :=
  [{outputs}]
def assumed ({aw} : W) : List F := [{assumed}]

/-- The module as a relation between its input and output lists. -/
def rel (ins outs : List F) : Prop :=
  ∃ w : W, constraints w ∧ inputs w = ins ∧ outputs w = outs

theorem st0 {{x0 : F}} : x0 = x0 := rfl

/-- Determinism. -/
theorem deterministic
{hyps}    (w w' : W) (hw : constraints w) (hw' : constraints w')
    (hin : inputs w = inputs w') (hassume : assumed w = assumed w') :
    {conclusion} := by
  picus_safe (
    sorry
  )

end {ns}
"""

TOP = """
/-! ### Module `top` -/
namespace top

structure W where
  /-- `is_add_0` -/
  v0 : F
  /-- `is_sub_1` -/
  v1 : F

def constraints_0 (w : W) : Prop :=
  (w.v0 * (w.v0 - (1 : F))) = 0 ∧
  (w.v1 * (w.v1 - (1 : F))) = 0

def constraints (w : W) : Prop :=
  constraints_0 w

def input_origins : List String := []
def output_origins : List String := []

def inputs (_w : W) : List F := []
def outputs (w : W) : List F :=
  [w.v0, w.v1]
def assumed (_w : W) : List F := []

def rel (ins outs : List F) : Prop :=
  ∃ w : W, constraints w ∧ inputs w = ins ∧ outputs w = outs

/-- Selector-shape / bit postconditions implied by the constraints. -/
theorem postconditions (w : W) (hw : constraints w) :
{post} := by
  sorry

end top
"""

HYP = "    (h_byte_and : ∀ i o o', byte_and.rel i o → byte_and.rel i o' → o = o') -- abstract helper: assumed\n"


def chip_file(chip="Toy", **kw):
    """A generated-looking chip file; keyword arguments override parts of the default module."""
    p = {
        "title": f"{chip}__is_op",
        "ns": f"{chip}_is_op",
        "fields": [(0, "pc_0"), (1, "a_1"), (2, "a_2"), (3, "b_3"), (4, None)],
        "constraints": ["(w.v4 - (w.v0 + (4 : F))) = 0", "(w.v3 - (w.v1 + w.v2)) = 0",
                        "(w.v1).val ≤ 255", "byte_and.rel [w.v1, w.v2] [w.v3]"],
        "inputs": [(0, "state_recv[0]"), (1, "mem_read[0].val[0]"), (2, "mem_read[0].val[1]")],
        "outputs": [(4, "state_send[0]"), (3, "mem_write[0].val[0]")],
        "assumed": [],
        "hyps": [HYP],
        "conclusion": "outputs w = outputs w'",
        "helper": "opaque rel : List F → List F → Prop",
        "post": ["(w.v0 * (w.v0 - (1 : F))) = 0", "(w.v1 * (w.v1 - (1 : F))) = 0", "((w.v0 + w.v1)).val < 2"],
        "extra": "",
    }
    p.update(kw)
    fields = []
    for idx, doc in p["fields"]:
        if doc is not None:
            fields.append(f"  /-- `{doc}` -/")
        fields.append(f"  v{idx} : F")
    text = HEADER.format(chip=chip) + HELPER.format(decl=p["helper"])
    text += MODULE.format(
        title=p["title"], ns=p["ns"], fields="\n".join(fields),
        constraints=" ∧\n".join("  " + c for c in p["constraints"]),
        in_origins=json.dumps([o for _, o in p["inputs"]]),
        out_origins=json.dumps([o for _, o in p["outputs"]]),
        inputs=", ".join(f"w.v{i}" for i, _ in p["inputs"]),
        outputs=", ".join(f"w.v{i}" for i, _ in p["outputs"]),
        aw="w" if p["assumed"] else "_w",
        assumed=", ".join(f"w.v{i}" for i in p["assumed"]),
        hyps="".join(p["hyps"]), conclusion=p["conclusion"])
    text += TOP.format(post=" ∧\n".join("    " + c for c in p["post"]))
    text += p["extra"]
    text += f"\nend ZirenDet.Chips.{chip}\n\n#print \"PICUS_FILE_DONE\"\n"
    return text


class PinTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name)

    def tearDown(self):
        self.tmp.cleanup()

    def tree(self, name, files):
        chips = self.root / name / "ZirenDet" / "Chips"
        chips.mkdir(parents=True)
        for chip, text in files.items():
            (chips / f"{chip}.lean").write_text(text)
        return str(self.root / name / "ZirenDet")

    def run_compare(self, old_files, new_files):
        """(number of weakenings, report) of comparing two synthetic trees."""
        old = pin.snapshot(self.tree("old", old_files))
        new = pin.snapshot(self.tree("new", new_files))
        out = io.StringIO()
        n = pin.compare(old, new, all_info=True, out=out)
        return n, out.getvalue()

    def assert_weak(self, new_kw, needle, old_kw=None):
        n, report = self.run_compare({"Toy": chip_file(**(old_kw or {}))}, {"Toy": chip_file(**new_kw)})
        self.assertGreater(n, 0, report)
        self.assertIn(needle, report)
        self.assertTrue(any(line.startswith("WEAKENING") and needle in line for line in report.splitlines()),
                        report)
        return report

    def assert_info_only(self, new_kw, needle, old_kw=None):
        n, report = self.run_compare({"Toy": chip_file(**(old_kw or {}))}, {"Toy": chip_file(**new_kw)})
        self.assertEqual(n, 0, report)
        self.assertIn(needle, report)
        return report

    def test_parse(self):
        man = pin.snapshot(self.tree("t", {"Toy": chip_file()}))
        mod = man["modules"]["Toy/Toy_is_op"]
        self.assertEqual(mod["inputs"], ["state_recv[0] <- pc", "mem_read[0].val[0] <- a",
                                         "mem_read[0].val[1] <- a"])
        self.assertEqual(mod["outputs"], ["state_send[0] <- derived", "mem_write[0].val[0] <- b"])
        self.assertEqual(mod["assumed"], [])
        det = mod["theorems"]["deterministic"]
        self.assertEqual(det["hypotheses"], ["(∀ i o o', byte_and.rel i o → byte_and.rel i o' → o = o')"])
        self.assertEqual(det["conclusion"], ["outputs w = outputs w'"])
        self.assertEqual(mod["constraints"]["range_facts"], 1)
        self.assertEqual(mod["constraints"]["helper_calls"], {"byte_and": 1})
        self.assertEqual(mod["other_theorems"], {"stN": 1})
        top = man["modules"]["Toy/top"]
        self.assertEqual(len(top["theorems"]["postconditions"]["conclusion"]), 3)
        self.assertEqual(man["modules"]["Toy/byte_and"]["kind"], "helper")
        self.assertNotIn(self.tmp.name, json.dumps(man))

    def test_identical(self):
        n, report = self.run_compare({"Toy": chip_file()}, {"Toy": chip_file()})
        self.assertEqual(n, 0)
        self.assertIn("0 with a changed pinned part", report)

    def test_assumed_grows_is_weakening(self):
        self.assert_weak({"assumed": [3]}, "assumed gained 1: col b#0")

    def test_assumed_shrinks_is_info(self):
        self.assert_info_only({}, "assumed lost 1", old_kw={"assumed": [3]})

    def test_input_gained_is_weakening(self):
        self.assert_weak({"inputs": [(0, "state_recv[0]"), (1, "mem_read[0].val[0]"),
                                     (2, "mem_read[0].val[1]"), (3, "mem_read[1].val[0]")]},
                         "inputs gained 1: mem_read[1].val[0]")

    def test_output_lost_is_weakening(self):
        self.assert_weak({"outputs": [(4, "state_send[0]")]}, "outputs lost 1: mem_write[0].val[0]")

    def test_output_gained_is_info(self):
        self.assert_info_only({"outputs": [(4, "state_send[0]"), (3, "mem_write[0].val[0]"),
                                           (2, "mem_write[0].val[1]")]}, "outputs gained 1")

    def test_new_hypothesis_is_weakening(self):
        extra = HYP.replace("byte_and", "byte_xor")
        self.assert_weak({"hyps": [HYP, extra]}, "hypothesis added: (∀ i o o', byte_xor.rel")

    def test_dropped_hypothesis_is_info(self):
        self.assert_info_only({"hyps": []}, "hypothesis dropped")

    def test_conclusion_change_is_weakening(self):
        self.assert_weak({"conclusion": "True"}, "conclusion changed")

    def test_module_removed_is_weakening(self):
        n, report = self.run_compare({"Toy": chip_file(), "Two": chip_file(chip="Two")},
                                     {"Toy": chip_file()})
        self.assertGreater(n, 0)
        self.assertIn("WEAKENING  Two/Two_is_op: module removed", report)

    def test_module_added_is_info(self):
        n, report = self.run_compare({"Toy": chip_file()},
                                     {"Toy": chip_file(), "Two": chip_file(chip="Two")})
        self.assertEqual(n, 0, report)
        self.assertIn("Two/Two_is_op: module added", report)

    def test_theorem_removed_is_weakening(self):
        old = chip_file()
        new = old.replace("theorem deterministic", "def deterministic_gone : Prop := True\ntheorem not_it")
        n, report = self.run_compare({"Toy": old}, {"Toy": new})
        self.assertGreater(n, 0)
        self.assertIn("theorem deterministic removed", report)

    def test_renumbered_columns_change_nothing_pinned(self):
        ren = {0: 10, 1: 11, 2: 12, 3: 13, 4: 14}
        kw = {
            "fields": [(10, "pc_10"), (11, "a_11"), (12, "a_12"), (13, "b_13"), (14, None)],
            "constraints": ["(w.v14 - (w.v10 + (4 : F))) = 0", "(w.v13 - (w.v11 + w.v12)) = 0",
                            "(w.v11).val ≤ 255", "byte_and.rel [w.v11, w.v12] [w.v13]"],
            "inputs": [(ren[i], o) for i, o in
                       [(0, "state_recv[0]"), (1, "mem_read[0].val[0]"), (2, "mem_read[0].val[1]")]],
            "outputs": [(14, "state_send[0]"), (13, "mem_write[0].val[0]")],
        }
        old = pin.snapshot(self.tree("old", {"Toy": chip_file()}))
        new = pin.snapshot(self.tree("new", {"Toy": chip_file(**kw)}))
        self.assertEqual(old["modules"], new["modules"])

    def test_constraint_change_is_info(self):
        self.assert_info_only({"constraints": ["(w.v4 - (w.v0 + (4 : F))) = 0", "(w.v3 - (w.v1 + w.v2)) = 0",
                                               "byte_and.rel [w.v1, w.v2] [w.v3]"]},
                              "constraints changed: conjuncts 4 -> 3, range facts 1 -> 0")

    def test_column_rename_is_info(self):
        self.assert_info_only({"fields": [(0, "pc_0"), (1, "lhs_1"), (2, "lhs_2"), (3, "b_3"), (4, None)]},
                              "witness columns renamed 1:1: a -> lhs")

    def test_new_aliasing_is_weakening(self):
        self.assert_weak({"outputs": [(4, "state_send[0]"), (1, "mem_write[0].val[0]")]},
                         "ports now share one column: in:mem_read[0].val[0] = out:mem_write[0].val[0]")

    def test_port_moved_to_another_column_is_weakening(self):
        self.assert_weak({"fields": [(0, "pc_0"), (1, "a_1"), (2, "a_2"), (3, "b_3"), (4, None), (5, "clk_5")],
                          "outputs": [(5, "state_send[0]"), (3, "mem_write[0].val[0]")]},
                         "output state_send[0] is carried by another column: derived -> clk")

    def test_helper_redefined_is_weakening(self):
        self.assert_weak({"helper": "def rel : List F → List F → Prop := fun _ _ => True"},
                         "helper relation redefined")

    def test_postcondition_lost_is_weakening(self):
        self.assert_weak({"post": ["(w.v0 * (w.v0 - (1 : F))) = 0", "(w.v1 * (w.v1 - (1 : F))) = 0"]},
                         "postconditions: conjunct lost: ((w.⟨is_add#0⟩ + w.⟨is_sub#0⟩)).val < 2")

    def test_axiom_is_weakening(self):
        self.assert_weak({"extra": "\naxiom cheat : False\n"}, "axiom declared: axiom cheat : False")

    def test_cli_exit_codes(self):
        old = self.tree("old", {"Toy": chip_file()})
        weak = self.tree("weak", {"Toy": chip_file(assumed=[3])})
        manifest = self.root / "old.json"
        buf = io.StringIO()
        with redirect_stdout(buf):
            self.assertEqual(pin.main(["snapshot", old]), 0)
        manifest.write_text(buf.getvalue())
        with redirect_stdout(io.StringIO()):
            self.assertEqual(pin.main(["compare", str(manifest), old]), 0)
            self.assertEqual(pin.main(["compare", str(manifest), weak]), 1)
        with redirect_stderr(io.StringIO()):
            self.assertEqual(pin.main(["compare", str(manifest), str(self.root / "missing")]), 2)
            self.assertEqual(pin.main(["snapshot"]), 2)


if __name__ == "__main__":
    unittest.main()
